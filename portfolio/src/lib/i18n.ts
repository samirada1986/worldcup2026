export type Dict = (typeof dict)['en']
export const t = (l: Locale): Dict => dict[l] as Dict

export function toFaDigits(s: string): string {
  return s.replace(/\d/g, (d) => '۰۱۲۳۴۵۶۷۸۹'[Number(d)])
}

/** Localise digits in user-entered strings such as "2022–2024". */
export const num = (l: Locale, v: string | number | null | undefined): string => {
  if (v === null || v === undefined) return ''
  const s = String(v)
  return l === 'fa' ? toFaDigits(s) : s
}

export const pad = (l: Locale, n: number) => num(l, String(n).padStart(2, '0'))

export const formatDate = (l: Locale, iso?: string | null, opts?: Intl.DateTimeFormatOptions) => {
  if (!iso) return ''
  return new Intl.DateTimeFormat(l === 'fa' ? 'fa-IR' : 'en-GB', opts ?? { year: 'numeric', month: 'long', day: 'numeric' }).format(
    new Date(iso),
  )
}

export const localePath = (l: Locale, path = '') => `/${l}${path === '/' ? '' : path}`
